import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../styles.css',import.meta.url),'utf8');
const app=readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
const puzzles=JSON.parse(readFileSync(new URL('../data/puzzles.json',import.meta.url),'utf8'));
assert.match(html,/content="v11"/);
assert.match(html,/>Сканворды</);
assert.match(html,/id="back-button"/);
assert.match(html,/id="menu-button"/);
assert.match(html,/id="theme-button"/);
assert.match(html,/id="hints-button"[^>]*>Подсказки</);
assert.match(html,/id="letter-tiles"/); assert.match(html,/id="confetti"/);
assert.match(html,/class="board-area"[\s\S]*?<\/section>\s*<section class="clue-bar"/,'the clue bar must touch the grid with no spacer between them');
assert.match(html,/id="previous-word"[\s\S]*id="current-clue"[\s\S]*id="next-word"/,'the full current clue must sit between previous/next controls');
assert.match(css,/--board-cols:\s*10/);
assert.match(css,/--board-rows:\s*7/);
assert.match(css,/grid-template-rows:\s*repeat\(var\(--board-rows\),/);
assert.match(app,/Math\.min\(\s*availableWidth\s*\/\s*cols\s*,\s*availableHeight\s*\/\s*rows\s*\)/,'runtime cell size must be min(availW/cols, availH/rows)');
assert.match(css,/grid-template-rows:\s*repeat\(2,/);
assert.match(css,/\.grid-cell\.answer\.is-active\{background:var\(--card\)\}/,'empty letter cells stay white instead of painting the current word');
assert.equal(puzzles.length,8,'ship eight curated originals');
assert.deepEqual(puzzles.map(p=>p.number),Array.from({length:puzzles.length},(_,i)=>i+1));
assert.ok(puzzles.every(p=>p.cols===10&&p.rows===7));
assert.ok(puzzles.every(p=>p.source==='hand-curated exact-cover'));
assert.ok(puzzles.every(p=>p.words.length>=15&&p.words.length<=20),'each newspaper block needs 15–20 clue cells');
assert.ok(puzzles.every(p=>p.words.some(w=>w.direction==='down')&&p.words.some(w=>w.direction==='left')&&p.words.some(w=>w.direction==='across')));
const allWords=puzzles.flatMap(p=>p.words);
assert.equal(new Set(allWords.map(w=>w.answer)).size,allWords.length,'no answer may repeat anywhere in the catalog');
assert.equal(new Set(allWords.map(w=>w.clue)).size,allWords.length,'every clue must be original');
assert.ok(allWords.every(w=>w.clue.length>=5&&w.clue.length<=14),'clues must fit fully inside one phone cell');
assert.doesNotMatch(app,/portraitBoard|viewPosition|viewArrow|rotated/,'the iPhone board must stay 10 columns by 7 rows');
assert.doesNotMatch(app,/is-wrong/,'must not flash wrong letters instantly');
assert.match(app,/sparkleWord/); assert.match(app,/launchConfetti/);
assert.match(app,/window\.render_game_to_text/);
assert.doesNotMatch(css,/-webkit-line-clamp|text-overflow:\s*ellipsis/,'clue text may never be truncated');
assert.doesNotMatch(html,/generator\.js|words\.js/,'the failed generator pipeline must not ship');
console.log('scanword v11 acceptance checks passed');
