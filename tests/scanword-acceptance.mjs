import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const css=readFileSync(new URL('../styles.css',import.meta.url),'utf8');
const app=readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
const puzzles=JSON.parse(readFileSync(new URL('../data/puzzles.json',import.meta.url),'utf8'));
assert.match(html,/content="v9"/);
assert.match(html,/>Сканворды</);
assert.match(html,/id="menu-button"/);
assert.match(html,/id="zoom-out"[^>]*>[\s\S]*?−/);
assert.match(html,/id="zoom-in"[^>]*>[\s\S]*?крупнее/i);
assert.match(html,/id="theme-button"/);
assert.match(html,/id="hints-button"[^>]*>Подсказки</);
assert.match(html,/id="letter-tiles"/); assert.match(html,/id="confetti"/);
assert.match(html,/class="board-area"[\s\S]*?<\/section>\s*<section class="clue-bar"/,'the clue bar must touch the grid with no spacer between them');
assert.match(css,/--board-cols:\s*7/);
assert.match(css,/--board-rows:\s*10/);
assert.match(css,/\.grid-cell\.answer\{[^}]*font-size:\s*clamp\(22px,/s,'answer letters must start at 22px');
assert.match(css,/\.clue-text\{[^}]*font-size:\s*clamp\(14px,/s,'clue cells must start at 14px');
assert.match(css,/grid-template-rows:\s*repeat\(2,/);
assert.match(app,/pointerdown/); assert.match(app,/pointermove/); assert.match(app,/pointerup/);
assert.match(app,/setZoom/); assert.match(app,/Math\.min\(2\.2/);
assert.ok(puzzles.length>=7,'keep the puzzle catalog');
assert.ok(puzzles.every(p=>p.cols===7&&p.rows===10),'default boards must use large 7×10 cells');
assert.ok(puzzles.every(p=>p.words.length>=8&&p.words.length<=12),'default puzzle should contain only 8–12 words');
assert.ok(puzzles.every(p=>p.words.some(w=>w.direction==='down')&&p.words.some(w=>w.direction==='across')),'keep across and down answers');
const allWords=puzzles.flatMap(p=>p.words);
assert.equal(new Set(allWords.map(w=>w.answer)).size,allWords.length,'no answer may repeat anywhere in the catalog');
assert.equal(new Set(allWords.map(w=>w.clue)).size,allWords.length,'every clue must stay unique');
assert.doesNotMatch(app,/is-wrong/,'must not flash wrong letters instantly');
assert.match(app,/sparkleWord/); assert.match(app,/launchConfetti/);
assert.match(app,/window\.render_game_to_text/);
console.log('scanword v9 large-type acceptance checks passed');
